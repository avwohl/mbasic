PROLOGUES = {
    "plain": "",
    # file 1 for input (holds "hi"), file 2 random with records of 20 bytes
    "seq": '2 OPEN "O",#3,"zzin.dat":PRINT #3,"hi":CLOSE:OPEN "I",#1,"zzin.dat":OPEN "R",#2,"zzr.dat",20\n',
    # file 2 random, one record written
    "rec": '2 OPEN "R",#2,"zzr.dat",20:FIELD #2,10 AS A$,10 AS B$:LSET A$="a":PUT #2,1\n',
}


def file_program(prologue, statement):
    return ('1 ON ERROR GOTO 900\n' + PROLOGUES[prologue] + '10 ' + statement +
            '\n20 PRINT "ok"\n30 SYSTEM\n900 PRINT "E";ERR;ERL:RESUME NEXT\n')


def compile_js(tmp_path, source):
    basic = tmp_path / "prog.bas"
    basic.write_text(source)
    output = tmp_path / "prog.js"
    result = subprocess.run(
        [sys.executable, str(ROOT / "mbasic"), str(basic), "--compile-js", str(output)],
        cwd=ROOT, capture_output=True, text=True, timeout=30,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    return output


def run_js(tmp_path, source):
    output = compile_js(tmp_path, source)
    result = subprocess.run([NODE, str(output)], cwd=tmp_path, capture_output=True, text=True, timeout=10)
    return result.stdout.rstrip("\n") + "\n"


def run_interpreter(tmp_path, source):
    basic = tmp_path / "prog.bas"
    basic.write_text(source)
    result = subprocess.run(
        [sys.executable, str(ROOT / "mbasic"), str(basic), "--ui", "cli"],
        input="RUN\nSYSTEM\n", cwd=tmp_path, capture_output=True, text=True, timeout=30)
    text = result.stdout.replace("\r", "")
    return text.split("\nOk\n", 1)[1].split("\nOk\n")[0].replace("Goodbye", "").rstrip("\n") + "\n"


@pytest.mark.parametrize("name,source,expected", PROGRAMS, ids=[p[0] for p in PROGRAMS])
def test_program_js(tmp_path, name, source, expected):
    assert run_js(tmp_path, source) == expected


@pytest.mark.parametrize("name,source,expected", PROGRAMS, ids=[p[0] for p in PROGRAMS])
def test_program_interpreter(tmp_path, name, source, expected):
    assert run_interpreter(tmp_path, source) == expected


def test_lset_on_a_plain_variable_keeps_its_length(tmp_path):
    # Measured: LSET G$="x" on an empty G$ leaves "" (a plain variable keeps its length); F$ is a field
    source = ('10 OPEN "R",#1,"zzq.dat",20\n20 FIELD #1,10 AS F$\n30 LSET G$="x":LSET F$="hi"\n'
              '40 PRINT "[";F$;"][";G$;"]"\n50 CLOSE\n')
    assert run_js(tmp_path, source) == "[hi        ][]\n"


